export function resolveDashboardProduct(
  productIdOrItemId: string
): ModasrProduct {
  const existing = MODASR_PRODUCTS.find((p) => p.id === productIdOrItemId);
  if (existing) return existing;
  if (EXTRA_DASHBOARD_PRODUCTS[productIdOrItemId]) {
    return EXTRA_DASHBOARD_PRODUCTS[productIdOrItemId];
  }
  return EXTRA_DASHBOARD_PRODUCTS['custom-website-order'];
}

